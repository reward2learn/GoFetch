/**
 * Get a destination image URL for a given country or city name.
 * Falls back to a generic travel image if no match is found.
 */
export function getCountryImage(countryOrCity: string): string {
  // Try exact match first
  if (countryImages[countryOrCity]) {
    return countryImages[countryOrCity];
  }

  // Try case-insensitive match
  const lower = countryOrCity.toLowerCase();
  for (const [key, url] of Object.entries(countryImages)) {
    if (key.toLowerCase() === lower) {
      return url;
    }
  }

  // Fallback: generic travel/destination image
  return "https://images.unsplash.com/photo-1488646953014-85cb44e25828?w=400&h=300&fit=crop";
}
